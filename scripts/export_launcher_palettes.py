#!/usr/bin/env python3
"""Export approved palette masters to native adaptive layers and Settings previews.

Run after export_launcher_icons.py if the shared mark geometry changes.
Requires rsvg-convert. The originals and their exact SVG proofs are preserved.
"""
from copy import deepcopy
import json
import xml.etree.ElementTree as ET
from export_launcher_icons import ANDROID, AAPT, ART, RES, embedded_png, rasterize, svg


def main():
    ET.register_namespace("android", ANDROID[1:-1])
    ET.register_namespace("aapt", AAPT[1:-1])
    template = ET.parse(RES / "drawable/ic_launcher_foreground.xml").getroot()
    for name in ["dawn", "day", "dusk", "night"]:
        source = ART / "palette-studies" / name
        palette = json.loads((source / "selection.json").read_text())["palette"]
        vector = deepcopy(template)
        edge, letter, star = list(vector.iter("path"))
        letter.set(ANDROID + "fillColor", palette["f"])
        star.set(ANDROID + "fillColor", palette["star"])
        for item in edge.iter("item"):
            old = item.get(ANDROID + "color")
            item.set(ANDROID + "color", old[:3] + palette["edge"][1:])
        ET.indent(vector, space="    ")
        (RES / f"drawable/ic_launcher_{name}_foreground.xml").write_text(
            '<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by scripts/export_launcher_palettes.py. -->\n'
            + ET.tostring(vector, encoding="unicode") + "\n"
        )
        # Assert that every native contour still matches the approved SVG master.
        proof = ET.parse(source / "foreground.svg").getroot()
        proof_paths = list(proof.iter("{http://www.w3.org/2000/svg}path"))
        assert [p.get(ANDROID + "pathData") for p in vector.iter("path")] == [
            p.get("d") for p in proof_paths
        ], f"{name}: approved geometry differs from native geometry"
        background = f'<image width="108" height="108" xlink:href="{embedded_png(source / "background.png")}"/>'
        rasterize(svg(background), RES / f"drawable-nodpi/foliore_landscape_{name}.png", 432)
        (RES / f"drawable/ic_launcher_{name}_background.xml").write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<bitmap xmlns:android="http://schemas.android.com/apk/res/android"
    android:src="@drawable/foliore_landscape_{name}"
    android:gravity="fill"
    android:filter="true" />
''')
        (RES / f"mipmap-anydpi-v26/ic_launcher_{name}.xml").write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_{name}_background" />
    <foreground android:drawable="@drawable/ic_launcher_{name}_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
''')
        # Only the in-app preview is masked. Launcher layers retain all overscan.
        mark = (source / "foreground.svg").read_text().split(">", 1)[1].rsplit("</svg>", 1)[0]
        rasterize(svg(
            '<g clip-path="url(#preview)">' + background + mark + '</g>',
            "18 18 72 72",
            defs='<clipPath id="preview"><rect x="18" y="18" width="72" height="72" rx="16"/></clipPath>',
        ), RES / f"drawable-nodpi/ic_launcher_{name}_preview.png", 192)
        print(f"Exported {palette['name']}")


if __name__ == "__main__":
    main()
